#!/usr/bin/env python3
"""Inventory every canonical vowel-initial verb without inventing stem classes.

The 48-item frozen Batch 05 intake is a floor, not the total current lexicon.
This is a read-only audit of canonical sources, not a new morphology engine.
"""
import argparse
import json
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/"docs/VOWEL_INITIAL_VERB_INVENTORY_2026_10_29.md"
VOWEL=re.compile(r"^[aeiouāēīōū]",re.IGNORECASE)

def read(relative):
    return json.loads((ROOT/relative).read_text(encoding="utf-8"))

def describe(word):
    pos=str(word.get("pos") or "")
    claims={c.get("field"):c for c in word.get("claims",[])}
    stem=claims.get("stem",{})
    exact=[i for i in word.get("inflections",[])
           if i.get("evidence") in ("dictionary","text")
           and re.match(r"^Preterite 1sg(?:\b|[,(])",i.get("category",""),re.I)]
    lemma=word["word"]
    first=next((c for c in [claims.get("headword",{}),claims.get("pos",{})]
               if c.get("assessment") not in ("dictionary","grammar","text")),None)
    checked=(first is None and
             all(claims.get(f,{}).get("assessment") in ("dictionary","grammar","text")
                 for f in ("headword","pos")))
    direct=pos=="verb (intransitive)"
    same_vowel=[x for x in exact if re.match(r"^(?:o|ō)n",x["form"],re.I)
                and x["form"][2:3].lower()==lemma[:1].lower()]
    return dict(word=lemma,pos=pos,review=word.get("status",""),
                source=claims.get("headword",{}).get("source",""),
                locator=claims.get("headword",{}).get("locator",""),
                past=", ".join(x["form"] for x in exact) or "—",
                stem=stem.get("assessment","unverified") or "unverified",
                use=("direct n-/t- + verified 1sg template" if direct and checked and same_vowel
                     else "direct n-/t- present only" if direct and checked
                     else "withheld: provisional" if not checked
                     else "withheld: valency/object/independent stem"))
def generate():
    dictionary=read("dictionary.json")
    intake=read("research/batches/classical_archive_verb_batch05_2026_10_29.json")
    batch={x["word"] for x in intake["entries"] if VOWEL.search(x["word"])}
    assert len(batch)==48,"Frozen Batch 05 48-item vowel inventory changed"
    words=[w for w in dictionary["words"]
           if VOWEL.search(w["word"]) and str(w.get("pos","")).startswith("verb")]
    assert batch.issubset({w["word"] for w in words}),"Some archived vowel-initial verb identities disappeared"
    words=sorted(words,key=lambda x:x["word"])
    rows=[describe(w) for w in words]
    lines=["# Complete canonical vowel-initial verb audit (2026-10-29)","",
      "Generated by `python tools/audit_vowel_initial_verbs.py --write`; verify with `--check`.",
      "This audits **all** current canonical verb-labelled headwords beginning with a written",
      "a/e/i/o/u (including macron-bearing vowels), not just the initial 48 in",
      "the frozen 268-verb Batch 05 archive intake.","",
      "## Grammar versus lexical evidence","",
      "Launey (2011), *An Introduction to Classical Nahuatl*, §1.2:",
      "the subject markers are **n-/t- directly before a vowel**, and **ni-/ti- before a consonant**.",
      "A vowel-initial *headword* does not mean the same allomorph can be used",
      "before intervening transitive-object or reflexive morphology.",
      "Separate weak-initial-i deletion and long-vowel mismatches are **not licensed**.",
      "An exact dictionary-listed 1sg token can support a restricted 2sg",
      "subject replacement, but does not license a Class 1/2 stem by itself.",
      "Source claim levels and exact words below remain unchanged.","",
      f"Total canonical vowel-initial verb-labelled identities: **{len(rows)}**.",
      f"Of those, **{len(batch)}** are in the frozen Batch 05 initial intake.",
      f"Explicitly reviewed intransitives with a source-listed, identical-vowel 1sg preterite: "
      f"**{sum(r['use']=='direct n-/t- + verified 1sg template' for r in rows)}**.","",
      "| Headword | Lexical POS | Review | Exact sourced 1sg past | Stem claim | Scope |",
      "|---|---|---|---|---|---|"]
    for r in rows:
        name=r["word"].replace("|","\\|")
        source=r["source"]
        name=f"[{name}]({source})" if source.startswith("https://") else name
        lines.append("| "+ " | ".join((name,r["pos"],r["review"],r["past"],
                                         r["stem"],r["use"]))+" |")
    lines+=["",
      "## Source hierarchy and limits","",
      "- [Launey, *An Introduction to Classical Nahuatl* §1.2](https://api.pageplace.de/preview/DT0400.9780511985027_A23683606/preview-9780511985027_A23683606.pdf).",
      "- [Karttunen, *An Analytical Dictionary of Nahuatl*, introduction](https://mexika.org/wp-content/uploads/2013/09/nahuatldictionary.pdf): weak initial (I) sometimes drops, but not for every stem.",
      "- [ODN: iztlacati](https://nahuatl.wired-humanities.org/content/iztlacati) records ōniztlacat; [ODN: ichtequi](https://nahuatl.wired-humanities.org/content/ichtequi) records ōnichtec and distinct transitive ōniquichtec.",
      "- Historical lexical forms and algorithmic hypotheses must never be labelled as independent manuscript attestations or verified translations.",
      "- Missing source-verified stem classes remain unresolved; provisional archive entries cannot be promoted from spelling alone.",""]
    return "\n".join(lines)
def main():
    parser=argparse.ArgumentParser()
    group=parser.add_mutually_exclusive_group()
    group.add_argument("--write",action="store_true")
    group.add_argument("--check",action="store_true")
    a=parser.parse_args()
    expected=generate()
    if a.write:
        OUT.write_text(expected,encoding="utf-8")
        print("UPDATED",OUT.relative_to(ROOT))
    else:
        assert OUT.exists() and OUT.read_text(encoding="utf-8")==expected, "Vowel-initial inventory is stale"
        print("PASS comprehensive vowel-initial inventory")
if __name__=="__main__":main()
